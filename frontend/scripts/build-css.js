/*
 * Bundles public/css/main.css (a list of @imports, each a separate request) into one file, public/css/app.css,
 * so a page loads its styles in one request instead of a chain of thirteen.  npm run build:css
 * `--check` exits 1 when the committed bundle is out of date (used by the test suite).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'public', 'css');
function bundle() {
  const entry = fs.readFileSync(path.join(root, 'main.css'), 'utf8');
  const parts = [...entry.matchAll(/@import url\('([^']+)'\);/g)].map(m => `/* ${m[1]} */\n${fs.readFileSync(path.join(root, m[1]), 'utf8').trim()}`);
  return `/* GENERATED by frontend/scripts/build-css.js from main.css: edit the source files, then run npm run build:css */\n${parts.join('\n\n')}\n`;
}

const out = path.join(root, 'app.css');
const next = bundle();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== next) { console.error('public/css/app.css is out of date. Run: npm run build:css'); process.exit(1); }
  console.log('app.css is up to date.');
} else {
  fs.writeFileSync(out, next);
  console.log(`Wrote ${out} (${next.length} bytes)`);
}
module.exports = { bundle };
